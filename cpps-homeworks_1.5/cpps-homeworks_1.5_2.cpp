#include <iostream>
#include <limits> // для std::numeric_limits

int main() {
    // Создаем и инициализируем массив из 10 целых чисел
    int arr[10] = {5, 12, -3, 8, 0, 25, -7, 15, 9, 4};

    // Выводим элементы массива на экран
    std::cout << "Массив: ";
    for (int i = 0; i < 10; ++i) {
        std::cout << arr[i] << " ";
    }
    std::cout << std::endl;

    // Находим минимальный и максимальный элементы массива

    // Инициализируем минимум и максимум первым элементом массива
    int min_val = arr[0];
    int max_val = arr[0];

    // Проходим по массиву, начиная со второго элемента
    for (int i = 1; i < 10; ++i) {
        // Если текущий элемент меньше текущего минимума, обновляем минимум
        if (arr[i] < min_val) {
            min_val = arr[i];
        }

        // Если текущий элемент больше текущего максимума, обновляем максимум
        if (arr[i] > max_val) {
            max_val = arr[i];
        }
    }

    // Выводим минимальный и максимальный элементы на экран
    std::cout << "Минимальный элемент: " << min_val << std::endl;
    std::cout << "Максимальный элемент: " << max_val << std::endl;

    return 0;
}
